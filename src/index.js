const rootElement = document.getElementById('root');

// react-snap pre-renders static HTML for each route at build time. When that
// HTML is present (root already has children), hydrate it so React reuses the
// markup; otherwise fall back to a normal client-side render. This keeps the
// app working identically whether or not the prerender step ran.
if (rootElement.hasChildNodes()) {
  ReactDOM.hydrateRoot(
    rootElement,
    <React.StrictMode>
      <App />
    </React.StrictMode>
  );
} else {
  ReactDOM.createRoot(rootElement).render(
    <React.StrictMode>
      <App />
    </React.StrictMode>
  );
}

